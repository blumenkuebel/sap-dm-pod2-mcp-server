  "| Widget | `sap/dm/dme/pod2/widget/Widget` | `_createView()`, `onInit()`, `onExit()` |",
  "| Action | `sap/dm/dme/pod2/action/Action` | `execute(oActionContext)` |",
  "",
  "## Widget Subtypes",
